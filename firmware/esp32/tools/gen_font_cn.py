#!/usr/bin/env python3
"""Generate a 16x16 CJK subset for the SSD1306 UI (font_cn.h).

Glyphs derived from Noto Sans CJK SC (SIL Open Font License 1.1).
"""
from PIL import Image, ImageDraw, ImageFont

CHARS = "今日该喝水了刚秤配对中目标达成连接换杯单静音电量长按"
FONT = "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc"

def glyph(ch):
    img = Image.new("L", (16, 16), 0)
    d = ImageDraw.Draw(img)
    f = ImageFont.truetype(FONT, 15, index=2)  # SC face
    d.text((0, 0), ch, font=f, fill=255, anchor="la")
    rows = []
    for y in range(16):
        hi = lo = 0
        for x in range(16):
            if img.getpixel((x, y)) > 110:
                if x < 8:
                    hi |= 1 << (7 - x)
                else:
                    lo |= 1 << (15 - x)
        rows.append((hi, lo))
    return rows

lines = ["/* auto-generated by tools/gen_font_cn.py — do not edit */",
         "#pragma once", "#include <stdint.h>", "",
         "typedef struct { const char *code; uint8_t bmp[32]; } cn_glyph_t;", "",
         "static const cn_glyph_t CN_GLYPHS[] = {"]
for ch in CHARS:
    rows = glyph(ch)
    data = []
    for hi, lo in rows:
        data += [hi, lo]
    lines.append(f'    {{"{ch}", {{{",".join("0x%02X" % b for b in data)}}}}},')
lines += ["};", "", f"#define CN_GLYPH_COUNT {len(CHARS)}", ""]
open("main/font_cn.h", "w", encoding="utf-8").write("\n".join(lines))
print("glyphs", len(CHARS), "bytes", len(CHARS) * 32, "-> main/font_cn.h")
