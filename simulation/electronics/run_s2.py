def run_ngspice(name, netlist, allow_warn=False):
    """Write netlist, run ngspice -b, return log text. Raises on errors."""
    cir = NETLISTS / f"{name}.cir"
    cir.write_text(netlist)
    log = LOGS / f"{name}.log"
    proc = subprocess.run([NGSPICE, "-b", "-o", str(log), str(cir)],
                          cwd=PROJECT, capture_output=True, text=True)
    txt = log.read_text(errors="replace") if log.exists() else proc.stdout
    bad = [ln for ln in txt.splitlines() if re.match(r"^\s*Error", ln)]
    if bad and not allow_warn:
        tail = "\n".join((proc.stderr or "").splitlines()[-6:] +
                         (txt.splitlines() or [])[-12:])
        raise RuntimeError(f"ngspice failed for {name} (rc={proc.returncode}):\n{tail}")
    # NOTE: ngspice -b returns 1 for .control-only netlists ("no .plot/.print
    # lines, no simulations run") even though the control block ran; only real
    # Error lines are treated as failures.
    return txt


VAL = r"([-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?)"


def parse_vals(log, name):
    """All 'name = value' scalar prints from a log, in order (floats)."""
    pat = re.compile(rf"(?m)^\s*{re.escape(name)}\s*=\s*{VAL}\s*$")
    return np.array([float(m.group(1)) for m in pat.finditer(log)])


def read_wr(name, nvec=1):
    """Read a wrdata file. Returns list of (x, y) arrays (one per vector)."""
    path = WORK / f"{name}.dat"
    arr = np.loadtxt(path, ndmin=2, dtype=float)
    return [(arr[:, 2 * i], arr[:, 2 * i + 1]) for i in range(nvec)]


