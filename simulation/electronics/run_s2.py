# MODULE 4: MCU interface (I2C / EN power-up / battery divider)
# ===========================================================================
def run_mcu():
    print("\n=== module: mcu_io ===")

    # ---- I2C rise time .tran ----
    cases = [(4700, 100e-12), (4700, 200e-12), (2200, 100e-12), (2200, 200e-12)]
    waveforms = {}
    per_case = {}
    for rp, cb in cases:
        tag = f"rp{int(rp)}_cb{int(cb*1e12)}p"
        name = f"mcu_i2c_{tag}"
        net = f"""* I2C rise time: Rp={rp} ohm, Cbus={cb*1e12:.0f} pF, open-drain SW
Vdd vdd 0 DC 3.3
Rp vdd sda {rp}
Cb sda 0 {cb:.6e}
S1 sda 0 ctrl 0 SWMOD
Vctrl ctrl 0 PWL(0 3.3 0.5u 3.3 0.501u 0 2u 0)
.model SWMOD SW(Ron=50 Roff=1e12 Vt=1.65)
.control
tran 0.25n 2u
wrdata {WORKREL}/i2c_{tag}.dat v(sda)
.endc
.end
"""
        run_ngspice(name, net)
        (t, vs), = read_wr(f"i2c_{tag}")
        tr = (crossing(t, vs, 0.7 * VDD) - crossing(t, vs, 0.3 * VDD)) * 1e9
        analytic = 0.8473 * rp * cb * 1e9
        per_case[tag] = dict(Rp_ohm=rp, Cbus_pF=round(cb * 1e12, 1),
                             rise_30_70_ns=round(float(tr), 2),
                             analytic_0p8473RC_ns=round(float(analytic), 2),
                             pass_100kHz=tr <= 1000.0, pass_400kHz=tr <= 300.0)
        waveforms[tag] = (t, vs)
    thr = [
        dict(metric="rise_time_standard_mode", limit="<= 1000 ns", unit="ns", source=SRC_I2C),
        dict(metric="rise_time_fast_mode", limit="<= 300 ns", unit="ns", source=SRC_I2C),
    ]
    # design intends 400 kHz (pinmap: OLED SCL 400 kHz)
    design_rate = 400.0
    fast_ok = all(v["pass_400kHz"] for v in per_case.values())
    standard_ok = all(v["pass_100kHz"] for v in per_case.values())
    passed = fast_ok if design_rate >= 400 else standard_ok
    fig, ax = plt.subplots(figsize=(7, 4))
    for tag, (t, vs) in waveforms.items():
        ax.plot(t * 1e9, vs, label=tag, lw=1.4)
    ax.axhline(0.3 * VDD, color="k", ls=":", lw=0.7)
    ax.axhline(0.7 * VDD, color="k", ls=":", lw=0.7)
    ax.set_xlabel("time (ns)")
    ax.set_ylabel("SDA (V)")
    ax.set_title("I2C bus rise time, 4.7k vs 2.2k pull-up, 100/200 pF")
    ax.legend(fontsize=7)
    fig_path = save_fig(fig, "i2c_rise")
    d = add_result("mcu_io", "i2c_rise",
                   inputs=dict(design_rate_kHz=design_rate, pullups_ohm=[4700, 2200],
                               bus_cap_pF=[100, 200], driver_Ron_ohm=50, VDD=VDD),
                   metrics=dict(cases=per_case,
                                standard_mode_all_pass=standard_ok,
                                fast_mode_all_pass=fast_ok,
                                fast_mode_4k7_100pF_ns=per_case["rp4700_cb100p"]["rise_30_70_ns"],
                                fast_mode_limit_ns=300.0),
                   thresholds=thr, passed=passed,
                   notes=("FINDING: with the BOM 4.7k pull-ups and 100 pF bus capacitance, "
                          "tr(30-70%) ~398 ns > 300 ns -> the intended 400 kHz I2C does NOT "
                          "meet Fast-mode timing. 200 pF is even worse (~796 ns). Standard-mode "
                          "100 kHz passes (<=1000 ns) for all tested cases. Recommendations: "
                          "(a) run the OLED at 100 kHz, or (b) change R3/R4 to 2.2k (186 ns @100pF; "
                          "still 373 ns @200pF -> keep bus cap <= ~150 pF and verify with scope). "
                          "I2C bus capacitance is an ASSUMPTION (module + traces); measure it."),
                   artifacts=dict(figure=fig_path))
    write_result(d, "mcu_i2c_rise.json")

    # ---- EN power-up .tran ----
    def en_wave(name, rint=None):
        extra = "" if rint is None else f"Rint 3v3 en {rint}\n"
        net = f"""* ESP32-S3 EN power-up RC (10k + 1uF)
V3V3 3v3 0 PWL(0 0 100u 3.3)
R1 3v3 en 10k
C1 en 0 1u
{extra}.control
tran 5u 60m
wrdata {WORKREL}/{name}.dat v(en)
.endc
.end
"""
        run_ngspice(f"mcu_{name}", net)
        (t, ve), = read_wr(name)
        return t, ve

    t, ve = en_wave("en_powerup")
    tau = crossing(t, ve, 0.632 * 3.3)
    t_vih = crossing(t, ve, 0.75 * 3.3)
    t_vil = crossing(t, ve, 0.25 * 3.3)
    t2, ve2 = en_wave("en_powerup_int45k", rint="45k")
    tau2 = crossing(t2, ve2, 0.632 * 3.3)
    t_vih2 = crossing(t2, ve2, 0.75 * 3.3)
    thr = [
        dict(metric="EN_tau", limit="~10 ms (10k x 1uF)", unit="ms",
             source="R1/C9 design values (pinmap)"),
        dict(metric="EN_release_time", limit="0 < t(VIH) <= 100 ms", unit="ms",
             source=SRC_ESP32S3 + "; EN must be released after 3V3 is stable"),
        dict(metric="EN_VIH", limit="2.475 V = 0.75*VDD", unit="V", source=SRC_ESP32S3),
    ]
    passed = 0 < t_vih * 1000 <= 100 and 8.0 <= tau * 1000 <= 12.0
    fig, ax = plt.subplots(figsize=(7, 4))
    ax.plot(t * 1000, ve, label="EN (10k + 1uF)")
    ax.plot(t2 * 1000, ve2, "--", label="EN with internal 45k pull-up")
    ax.axhline(2.475, color="k", ls=":", lw=0.8, label="VIH=0.75*VDD")
    ax.set_xlabel("time (ms)")
    ax.set_ylabel("EN (V)")
    ax.set_title("ESP32-S3 EN power-up RC (3V3 ramp 0->3.3 V in 100 us)")
    ax.legend(fontsize=8)
    fig_path = save_fig(fig, "en_powerup")
    d = add_result("mcu_io", "en_powerup",
                   inputs=dict(R_pullup_ohm=10000, C_nF=1000, VDD=VDD,
                               internal_pullup_ohm=[None, 45000], ramp_us=100),
                   metrics=dict(tau_ms=round(tau * 1000, 3),
                                t_VIH_ms=round(t_vih * 1000, 3),
                                t_VIL_ms=round(t_vil * 1000, 3),
                                tau_with_internal45k_ms=round(tau2 * 1000, 3),
                                t_VIH_with_internal45k_ms=round(t_vih2 * 1000, 3)),
                   thresholds=thr, passed=passed,
                   notes=("EN rises to VIH ~13.9 ms after 3V3 starts; with the ESP32-S3 internal "
                          "~45k pull-up (ASSUMPTION) it is ~11.3 ms. Both are well inside the "
                          "allowed power-up window; the RC also keeps EN low while 3V3 ramps. "
                          "Reset button shorts EN to GND. Internal pull-up value is an assumption."),
                   artifacts=dict(figure=fig_path))
    write_result(d, "mcu_en_powerup.json")

    # ---- battery divider .dc ----
    name = "mcu_battery_divider"
    net = f"""* battery voltage divider 100k/100k + 100nF ADC filter
Vbat bat 0 DC 3.7
R6 bat adc 100k
R7 adc 0 100k
C13 adc 0 100n
.control
dc Vbat 3.0 4.2 0.05
wrdata {WORKREL}/batdiv_dc.dat v(adc)
.endc
.end
"""
    run_ngspice(name, net)
    (vb, va), = read_wr("batdiv_dc")
    ratio = va / vb
    div_i_uA = vb / 200e3 * 1e6
    adc_fs = 3.1   # ASSUMPTION: ESP32-S3 12 dB attenuation full scale
    thr = [
        dict(metric="divider_ratio", limit="0.5 (100k/100k)", unit="V/V", source=SRC_PINMAP),
        dict(metric="ADC_pin_range", limit=f"0-{adc_fs} V (12 dB attenuation)", unit="V",
             source=SRC_ESP32S3 + " + ASSUMPTION 12 dB FS ~3.1 V"),
        dict(metric="divider_current", limit="<= 30 uA", unit="uA",
             source="power budget: <=1% of 3 mA (docs/08)"),
    ]
    passed = (abs(np.mean(ratio) - 0.5) < 0.001 and np.max(va) < adc_fs
              and np.max(div_i_uA) <= 30.0)
    # Monte Carlo: R6/R7 +/-1%
    n = 200
    lines = ["* battery divider Monte Carlo R+/-1%", "Vbat bat 0 DC 4.2",
             "R6 bat adc 100k", "R7 adc 0 100k", "C13 adc 0 100n", ".control"]
    for _ in range(n):
        r6 = 100e3 * RNG.uniform(0.99, 1.01)
        r7 = 100e3 * RNG.uniform(0.99, 1.01)
        lines += [f"alter R6 = {r6:.3f}", f"alter R7 = {r7:.3f}", "op",
                  "print v(adc)"]
    lines += [".endc", ".end"]
    run_ngspice("mcu_battery_divider_mc", "\n".join(lines))
    log = (LOGS / "mcu_battery_divider_mc.log").read_text(errors="replace")
    vadc_mc = parse_vals(log, "v(adc)")
    vb_inferred = vadc_mc * 2.0
    err_mV = (vb_inferred - 4.2) * 1000
    thr += [dict(metric="inferred_battery_error", limit="<= 2% (84 mV) from 1% resistors",
                 unit="mV", source="resistor tolerance propagation; project gauge requirement")]
    passed = passed and float(np.max(np.abs(err_mV))) <= 84.0
    fig, ax = plt.subplots(figsize=(6.5, 4))
    ax.hist(err_mV, bins=25, color="teal", alpha=0.85)
    ax.set_xlabel("inferred battery voltage error at 4.2 V (mV)")
    ax.set_ylabel("count / 200")
    ax.set_title("Battery divider Monte Carlo: R6/R7 +/-1% (200 runs)")
    fig_path = save_fig(fig, "battery_divider_mc")
    d = add_result("mcu_io", "battery_divider",
                   inputs=dict(R6_ohm=100e3, R7_ohm=100e3, C13_nF=100,
                               Vbat_range_V=[3.0, 4.2], adc_fs_assumption_V=adc_fs,
                               mc_n=n, R_tol_pct=1.0, seed=SEED),
                   metrics=dict(ratio_mean=round(float(np.mean(ratio)), 6),
                                adc_pin_at_4V2_V=round(float(np.max(va)), 4),
                                divider_current_uA=round(float(np.max(div_i_uA)), 2),
                                thevenin_ohm=50e3,
                                mc_error_max_mV=round(float(np.max(np.abs(err_mV))), 2),
                                mc_error_std_mV=round(float(np.std(err_mV, ddof=1)), 2)),
                   thresholds=thr, passed=passed,
                   notes=("DC + resistor-tolerance MC pass. 100k/100k draws ~21 uA and stays "
                          "inside the ADC range. Source impedance 50k is high, but C13=100nF "
                          "supplies the SAR sampling charge; DC leakage is the remaining risk "
                          "(see mcu_battery_divider_leakage). ADC full-scale 3.1 V is an "
                          "ASSUMPTION for 12 dB attenuation - verify with esp_adc_cal."),
                   artifacts=dict(figure=fig_path))
    write_result(d, "mcu_battery_divider.json")

    # ---- ADC leakage sensitivity ----
    name = "mcu_battery_divider_leakage"
    net = f"""* ADC input leakage error: Ileak sinks current at the ADC pin
Vbat bat 0 DC 4.2
R6 bat adc 100k
R7 adc 0 100k
C13 adc 0 100n
Ileak adc 0 DC 0
.control
dc Ileak 0 1u 0.05u
wrdata {WORKREL}/batdiv_leak.dat v(adc)
.endc
.end
"""
    run_ngspice(name, net)
    (ileak, va2), = read_wr("batdiv_leak")
    err_pin_mV = (va2 - 2.1) * 1000
    err_bat_mV = err_pin_mV * 2
    def err_at(cur):
        return float(np.interp(cur, ileak, err_bat_mV))
    thr = [
        dict(metric="leakage_induced_error", limit="<= 42 mV (1% of 4.2 V)", unit="mV",
             source="project battery gauge requirement; ADC leakage NOT specified in local docs -> ASSUMPTION"),
    ]
    passed = abs(err_at(0.2e-6)) <= 42.0 and abs(err_at(1e-6)) <= 42.0
    d = add_result("mcu_io", "battery_divider_leakage",
                   inputs=dict(R6_ohm=100e3, R7_ohm=100e3, leakage_uA=[0, 0.2, 0.5, 1.0],
                               Vbat=4.2),
                   metrics=dict(error_at_0p2uA_mV=round(err_at(0.2e-6), 2),
                                error_at_0p5uA_mV=round(err_at(0.5e-6), 2),
                                error_at_1uA_mV=round(err_at(1e-6), 2),
                                error_mV_per_uA=round(err_at(1e-6) / 1.0, 2)),
                   thresholds=thr, passed=passed,
                   notes=("RISK/FINDING: the 100k/100k divider has a 50 kohm Thevenin source; "
                          "every 0.1 uA of ADC input leakage adds 10 mV at the pin = 20 mV at "
                          "the battery. At 1 uA the error is ~100 mV (2.4 %). The exact ESP32-S3 "
                          "ADC leakage is not in the locally available datasheets, so this is a "
                          "conditional finding: measure it (or calibrate the gauge) before "
                          "trusting the uncalibrated reading. C13 does not remove DC leakage. "
                          "Mitigations: factory/field calibration, lower divider (e.g. 10k/10k "
                          "costs ~210 uA), or a buffered/op-amp divider."))
    write_result(d, "mcu_battery_divider_leakage.json")


