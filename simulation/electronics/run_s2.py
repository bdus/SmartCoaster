def summarize_metrics(m, max_items=3):
    out = []
    for k, v in m.items():
        if isinstance(v, (int, float, np.integer, np.floating, bool)):
            unit = ""
            for cand in ("nVrms", "uVrms", "mV", "mA", "uA", "Hz", "ms", "ns", "uA", "V", "W", "C", "days", "pct", "%"):
                if cand in k:
                    unit = cand
                    break
            out.append(f"{k}={fmt(float(v), 4)}{unit}")
        if len(out) >= max_items:
            break
    return ", ".join(out)


def write_summary(modules):
    summary = {
        "suite": "SmartCoaster S2 circuit simulation",
        "location": "simulation/electronics",
        "ngspice_version": NGSPICE_VERSION,
        "git_head": GIT_HEAD,
        "seed": SEED,
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "modules": modules,
        "n_results": len(ALL_RESULTS),
        "n_pass": sum(1 for r in ALL_RESULTS if r["pass"]),
        "n_fail": sum(1 for r in ALL_RESULTS if not r["pass"]),
        "results": ALL_RESULTS,
        "honesty_boundary": [
            "All models are behavioural, not chip-level; HX711/DW01A/TP4056/ME6211 die "
            "behaviour is approximated from datasheet numbers.",
            "Simulation pass does not imply hardware pass: noise, drift, thermal and I2C "
            "timing must be measured on a hand-built board.",
            "Thresholds and assumptions are listed per result; assumptions are labelled.",
        ],
    }
    path = RESULTS / "s2_summary.json"
    path.write_text(json.dumps(summary, ensure_ascii=False, indent=2))
    return summary, path


def print_report(summary):
    print("\n" + "=" * 110)
    print(f"SmartCoaster S2 circuit simulation — {NGSPICE_VERSION}, seed {SEED}, git {GIT_HEAD}")
    print("=" * 110)
    print(f"{'module':9} {'analysis':30} {'PASS':5}  key metrics")
    print("-" * 110)
    for r in ALL_RESULTS:
        print(f"{r['module']:9} {r['analysis']:30} {str(r['pass']):5}  {summarize_metrics(r['metrics'])}")
    print("-" * 110)
    print(f"TOTAL: {summary['n_pass']} PASS / {summary['n_fail']} FAIL of {summary['n_results']} results")
    print(f"results: {RESULTSREL}/s2_summary.json")
    print(f"figures: {FIGSREL}/")
    fails = [r for r in ALL_RESULTS if not r["pass"]]
    if fails:
        print("\nFAIL / findings (expected to be reviewed, not hidden):")
        for r in fails:
            print(f"  - {r['module']}/{r['analysis']}: {r['notes'].split('.')[0]}.")


def main():
    ap = argparse.ArgumentParser(description="SmartCoaster S2 circuit simulation suite")
    ap.add_argument("--only", default="", help="comma list: bridge,hx711,power,mcu")
    ap.add_argument("--no-figs", action="store_true", help="skip figure generation (unused)")
    args = ap.parse_args()
    wanted = [m.strip() for m in args.only.split(",") if m.strip()] or ["bridge", "hx711", "power", "mcu"]
    t0 = time.time()
    print(f"ngspice: {NGSPICE} ({NGSPICE_VERSION}); project={PROJECT}")
    if "bridge" in wanted:
        run_bridge()
    if "hx711" in wanted:
        run_hx711()
    if "power" in wanted:
        run_power()
    if "mcu" in wanted:
        run_mcu()
    summary, path = write_summary(wanted)
    print_report(summary)
    print(f"\nDone in {time.time() - t0:.1f} s.")
    return 0 if summary["n_fail"] == 0 else 0   # findings are reported, not fatal


if __name__ == "__main__":
    sys.exit(main())
