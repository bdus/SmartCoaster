def hx711_input_net(vsource, include_filter=True, load="Rload out 0 1G"):
    """HX711 input network: bridge Thevenin 500+500 to a 1.65 V CM node,
    R25/R26=1k input filters, C16=100n differential cap, then the amp.
    `vsource` is a line like 'Vd e2 mid DC 0 AC 1' inserted in series with the
    A+ leg (so no ideal source short-circuits the differential node pair)."""
    return f"""* HX711 behavioural front-end
.include {INC['hx711']}
Vdd vdd 0 DC {VDD}
Vss vss 0 DC 0
Vcm cm 0 DC {VDD/2:.4f} AC 0
Rth1 sp cm 500
Rth2 sn cm 500
Rf1 sp mid 1k
{vsource}
Rf2 sn inn 1k
C16 e2 inn 100n
Xamp e2 inn out vdd vss hx711_amp GAIN={HX711_GAIN} VOFF={VDD/2:.4f} ROUT=1k CFILT={'15.9u' if include_filter else '1p'}
{load}
"""


