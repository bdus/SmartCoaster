#!/usr/bin/env python3
"""Specctra DSN export / SES import for the 2-layer SmartCoaster board.

Stages, driven by `route_2l.sh`:

    route_2l.py export   # smartcoaster.kicad_pcb  -> build/smartcoaster_2l.dsn
    route_2l.py import   # build/smartcoaster_2l.ses -> routed board (both names)
    route_2l.py clean    # widen sub-rule tracks, drop dangling stubs, re-DRC

Why this exists: KiCad writes the Specctra DSN, Freerouting 2.5.0 does the
routing headless, and KiCad imports the session back.  The board is generated by
`gen_pcb.py` (unrouted); routing is the step that turns it into a manufacturable
board, so re-running `build.sh` stays reproducible.

Notes / gotchas baked in here:
  * The DSN is exported from `smartcoaster/smartcoaster.kicad_pcb` (canonical,
    freshly generated, unrouted).  The routed result is saved as both
    `smartcoaster.kicad_pcb` and `smartcoaster_2l.kicad_pcb` so the handoff file
    name keeps working; the project file is mirrored too.
  * A component *value* containing a double quote (J4 used to be `OLED 0.91"`)
    breaks the DSN export: KiCad writes the quote unescaped and Freerouting's
    parser desyncs, silently mis-placing the next footprint (it was U2/HX711).
    design.py now uses `OLED 0.91in`; export() asserts no bare quote survives.
  * Freerouting emits a handful of short segments at 0.1874 mm (< the 0.2 mm
    project minimum) and can leave one dangling stub.  import() widens the
    narrow segments and clean() deletes copper that DRC still reports as a
    dangling track end, then re-runs DRC until it converges.
"""

import json
import os
import re
import shutil
import subprocess
import sys

import pcbnew

HERE = os.path.dirname(os.path.abspath(__file__))
KDIR = os.path.abspath(os.path.join(HERE, '..'))
SDIR = os.path.join(KDIR, 'smartcoaster')
BOARD = os.path.join(SDIR, 'smartcoaster.kicad_pcb')
BOARD_2L = os.path.join(SDIR, 'smartcoaster_2l.kicad_pcb')
PRO = os.path.join(SDIR, 'smartcoaster.kicad_pro')
PRO_2L = os.path.join(SDIR, 'smartcoaster_2l.kicad_pro')
BUILD = os.path.join(KDIR, 'build')
DSN = os.path.join(BUILD, 'smartcoaster_2l.dsn')
SES = os.path.join(BUILD, 'smartcoaster_2l.ses')
DRC_RPT = os.path.join(BUILD, 'DRC_2l.rpt')

# board/project design rule (keep in sync with gen_sch.py's min_track_width)
MIN_TRACK_MM = 0.2


def die(msg):
    print('ERROR: ' + msg, file=sys.stderr)
    sys.exit(1)


def kicad_cli():
    for cand in (os.path.expanduser('~/.local/bin/kicad-cli'),
                 shutil.which('kicad-cli')):
        if cand and os.path.exists(cand):
            return cand
    die('kicad-cli not found')


def mirror_project():
    """Give smartcoaster_2l.kicad_pcb its own .kicad_pro (DRC reads it)."""
    pro = json.load(open(PRO, encoding='utf-8'))
    pro.setdefault('meta', {})['filename'] = os.path.basename(PRO_2L)
    with open(PRO_2L, 'w', encoding='utf-8') as f:
        json.dump(pro, f, indent=2)
    print(f'mirrored project -> {PRO_2L}')


def run_drc(board_path, report):
    subprocess.run([kicad_cli(), 'pcb', 'drc', '--format', 'report',
                    '--severity-all', '--units', 'mm',
                    '-o', report, board_path],
                   check=True, stdout=subprocess.DEVNULL,
                   stderr=subprocess.DEVNULL)
    txt = open(report, encoding='utf-8', errors='replace').read()
    m = re.search(r'\*\* Found (\d+) DRC violations \*\*', txt)
    n_viol = int(m.group(1)) if m else -1
    n_unc = len(re.findall(r'^\[unconnected_items\]', txt, re.M))
    return txt, n_viol, n_unc


def export():
    if not os.path.exists(BOARD):
        die(f'missing {BOARD} — run gen_pcb.py first')
    board = pcbnew.LoadBoard(BOARD)
    n_fp = len(board.GetFootprints())
    n_tr = len(board.GetTracks())
    if n_tr:
        # Routing an already-routed board would keep the old wires; refuse so a
        # stale result can never be mistaken for a fresh one.
        die(f'{BOARD} already has {n_tr} track objects; regenerate with gen_pcb.py')
    os.makedirs(BUILD, exist_ok=True)
    pcbnew.ExportSpecctraDSN(board, DSN)
    # Sanity-check the placement scope: a component value with an embedded '"'
    # comes out unescaped and desyncs Freerouting's parser (this is how U2/HX711
    # used to get silently mis-placed).  Every quoted PN must open and close.
    for i, line in enumerate(open(DSN, encoding='utf-8', errors='replace'), 1):
        if '(PN "' in line and line.count('"') != 2:
            die(f'DSN line {i}: unescaped quote in component value -> {line.strip()}')
        if '"""' in line:
            die(f'DSN line {i}: tripled quote in component value')
    print(f'exported {DSN} ({os.path.getsize(DSN)} B, {n_fp} footprints)')


def import_ses():
    if not os.path.exists(SES):
        die(f'missing {SES} — run Freerouting first (route_2l.sh)')
    if os.path.getsize(SES) < 512:
        die(f'{SES} is only {os.path.getsize(SES)} B — Freerouting returned an empty session')
    board = pcbnew.LoadBoard(BOARD)
    if not pcbnew.ImportSpecctraSES(board, SES):
        die('ImportSpecctraSES failed')

    # Freerouting emits a few short segments below the 0.2 mm project minimum
    # (0.1874 mm); widen them so track_width DRC is clean.  Widening 12.6 µm
    # never created a clearance violation on this board.
    narrow = 0
    for t in board.GetTracks():
        if isinstance(t, pcbnew.PCB_VIA):
            continue
        if t.GetWidth() < pcbnew.FromMM(MIN_TRACK_MM):
            t.SetWidth(pcbnew.FromMM(MIN_TRACK_MM))
            narrow += 1

    n_tr = len(board.GetTracks())
    print(f'imported {SES}: {n_tr} tracks/vias, widened {narrow} sub-{MIN_TRACK_MM}mm tracks')
    pcbnew.SaveBoard(BOARD, board)
    pcbnew.SaveBoard(BOARD_2L, board)
    mirror_project()
    print(f'saved {BOARD} and {BOARD_2L}')


def _same_net_items(board):
    """All pads + track/via objects with a net, keyed by net code."""
    items = {}
    for fp in board.GetFootprints():
        for pad in fp.Pads():
            if pad.GetNetCode() > 0:
                items.setdefault(pad.GetNetCode(), []).append(pad)
    for t in board.GetTracks():
        if t.GetNetCode() > 0:
            items.setdefault(t.GetNetCode(), []).append(t)
    return items


def _uuid(it):
    """Stable identity for pcbnew wrappers (each GetTracks() call re-wraps)."""
    return it.m_Uuid.AsString()


def _touches(pt, netcode, items, exclude_uuid):
    """True if some *other* same-net item's copper covers `pt`."""
    for it in items.get(netcode, ()):
        if _uuid(it) == exclude_uuid:
            continue
        if it.HitTest(pt):
            return True
    return False


def _prune_pass(board):
    """Delete dangling track stubs and one-sided vias. Returns (ntracks, nvias).

    Freerouting occasionally ends a wire in free space (a 0.2 mm stub) or leaves
    a via with track on only one layer.  A segment with a free end cannot be the
    only path to anything, so removing it is connectivity-safe; iterate until a
    fixpoint because a chain of stubs can collapse one after another.
    """
    items = _same_net_items(board)
    rm_t, rm_v = [], []
    for t in board.GetTracks():
        nc = t.GetNetCode()
        if nc <= 0:
            continue
        tuid = _uuid(t)
        if isinstance(t, pcbnew.PCB_VIA):
            has = {pcbnew.F_Cu: False, pcbnew.B_Cu: False}
            for it in items.get(nc, ()):
                if _uuid(it) == tuid or isinstance(it, (pcbnew.PCB_VIA, pcbnew.PAD)):
                    continue
                if it.HitTest(t.GetPosition()):
                    has[it.GetLayer()] = True
            if not (has[pcbnew.F_Cu] and has[pcbnew.B_Cu]):
                rm_v.append(t)
        else:
            if not (_touches(t.GetStart(), nc, items, tuid)
                    and _touches(t.GetEnd(), nc, items, tuid)):
                rm_t.append(t)
    for t in rm_t + rm_v:
        board.Remove(t)
    return len(rm_t), len(rm_v)


def clean():
    """Widen sub-rule tracks, prune dangling stubs/vias, then require 0/0 DRC."""
    for attempt in range(6):
        board = pcbnew.LoadBoard(BOARD_2L)
        nt, nv = _prune_pass(board)
        if not (nt or nv):
            print(f'clean: no dangling copper left after {attempt} pass(es)')
            break
        pcbnew.SaveBoard(BOARD, board)
        pcbnew.SaveBoard(BOARD_2L, board)
        print(f'clean: pass {attempt + 1} removed {nt} dangling track(s), {nv} dangling via(s)')
    else:
        die('clean: dangling copper did not converge in 6 passes')

    txt, n_viol, n_unc = run_drc(BOARD_2L, DRC_RPT)
    m = re.search(r'\*\* Found (\d+) unconnected pads \*\*', txt)
    n_unc = int(m.group(1)) if m else -1
    kinds = re.findall(r'^\[([a-z_]+)\]', txt, re.M)
    print(f'clean: DRC violations={n_viol}, unconnected pads={n_unc}, kinds={sorted(set(kinds))}')
    if n_viol != 0 or n_unc != 0:
        die(f'clean: DRC not clean (violations={n_viol}, unconnected={n_unc}) — see {DRC_RPT}')


def main():
    stage = sys.argv[1] if len(sys.argv) > 1 else ''
    if stage == 'export':
        export()
    elif stage == 'import':
        import_ses()
    elif stage == 'clean':
        clean()
    else:
        die('usage: route_2l.py export|import|clean')


if __name__ == '__main__':
    main()
